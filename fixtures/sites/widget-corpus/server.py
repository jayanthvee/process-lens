def _attr(value: object) -> str:
    """A value, safe inside a double-quoted attribute."""
    return html.escape(str(value or ""), quote=True)


def _switches_script(state: FixtureState) -> str:
    # "<" is escaped so a switch value can never close the script element.
    blob = json.dumps(state.switches_snapshot(), sort_keys=True).replace("<", "\\u003c")
    return f"<script>window.__SWITCHES__ = {blob};</script>"


def _page(state: FixtureState, name: str) -> str:
    text = (PUBLIC / name).read_text(encoding="utf-8")
    return text.replace(SWITCH_TOKEN, _switches_script(state))


def render_index(state: FixtureState) -> str:
    """index.html: the hub. Every widget is linked, and every widget links back."""
    rows = "\n".join(
        f'<li><a data-testid="widget-link" href="{path.lstrip("/")}">{path.lstrip("/")}</a> '
        f'<span class="hint">&mdash; {html.escape(what)}</span></li>'
        for path, _source, what in WIDGET_PAGES
    )
    return INDEX_TEMPLATE.replace("<!--LINKS-->", rows).replace(
        SWITCH_TOKEN, _switches_script(state)
    )


def render_frame_child(state: FixtureState) -> str:
    """The same-origin frame's own document, served by this fixture."""
    _ = state  # the frame needs no switches of its own; the parent injects them
    return FRAME_CHILD_TEMPLATE


