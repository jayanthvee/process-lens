class _FixtureHandler(BaseHTTPRequestHandler):
    server_version = "WidgetCorpusFixture/1.0"
    sys_version = ""
    protocol_version = "HTTP/1.1"

    # -- plumbing ---------------------------------------------------------
    @property
    def state(self) -> FixtureState:
        return self.server.state  # type: ignore[attr-defined]

    def log_message(self, fmt: str, *args) -> None:
        sys.stderr.write(f"{self.address_string()} - {fmt % args}\n")

    def _send(self, status: int, body: bytes, content_type: str) -> None:
        self.send_response(status)
        self.send_header("Content-Type", content_type)
        self.send_header("Content-Length", str(len(body)))
        self.send_header("Cache-Control", "no-store")
        self.end_headers()
        if self.command != "HEAD":
            self.wfile.write(body)

    def _send_html(self, status: int, text: str) -> None:
        self._send(status, text.encode("utf-8"), "text/html; charset=utf-8")

    def _send_json(self, status: int, payload) -> None:
        self._send(status, json.dumps(payload).encode("utf-8"), "application/json; charset=utf-8")

    def _read_body(self) -> bytes:
        try:
            length = int(self.headers.get("Content-Length") or 0)
        except ValueError:
            length = 0
        if length <= 0:
            return b""
        return self.rfile.read(min(length, MAX_BODY))

    def _read_json(self) -> dict | None:
        raw = self._read_body()
        if not raw:
            return {}
        try:
            parsed = json.loads(raw.decode("utf-8"))
        except (UnicodeDecodeError, json.JSONDecodeError):
            return None
        return parsed if isinstance(parsed, dict) else None

    def _sleep_ms(self, value: object) -> None:
        """A switch-driven delay, capped so a bad patch cannot hang a run."""
        if isinstance(value, int) and value > 0:
            time.sleep(min(value, 30000) / 1000.0)

    def _static(self, name: str, content_type: str) -> None:
        path = PUBLIC / name
        if not path.is_file():
            self._not_found()
            return
        self._send(200, path.read_bytes(), content_type)

    def _not_found(self) -> None:
        self._send_html(
            404,
            "<!DOCTYPE html><html><head><title>Not found</title></head>"
            "<body><h1>Not found</h1></body></html>",
        )


class WidgetCorpusHandler(_FixtureHandler):
    """The only origin: pages, the sends, the directory and the test API."""

    # -- GET --------------------------------------------------------------
    def do_GET(self) -> None:  # noqa: N802 - stdlib signature
        parsed = urlparse(self.path)
        route = parsed.path

        if route == "/__test__/state":
            self._send_json(200, self.state.state_payload())
        elif route in ("/", "/index.html", "/index"):
            self._send_html(200, render_index(self.state))
        elif route == "/iframe-child.html":
            self._send_html(200, render_frame_child(self.state))
        elif route in PAGE_FILES:
            self._send_html(200, _page(self.state, PAGE_FILES[route]))
        elif route == "/directory.json":
            self._handle_directory(parsed)
        elif route == "/app.js":
            self._static("app.js", "text/javascript; charset=utf-8")
        elif route == "/compose-app.js":
            self._static("compose-app.js", "text/javascript; charset=utf-8")
        elif route == "/editors.js":
            self._static("editors.js", "text/javascript; charset=utf-8")
        elif route == "/autocomplete.js":
            self._static("autocomplete.js", "text/javascript; charset=utf-8")
        elif route == "/shadow.js":
            self._static("shadow.js", "text/javascript; charset=utf-8")
        elif route == "/styles.css":
            self._static("styles.css", "text/css; charset=utf-8")
        elif route == "/favicon.ico":
            self._send(204, b"", "image/x-icon")
        else:
            self._not_found()

    # -- POST -------------------------------------------------------------
    def do_POST(self) -> None:  # noqa: N802 - stdlib signature
        route = urlparse(self.path).path

        if route == "/send":
            self._handle_send()
        elif route == "/save":
            self._handle_save()
        elif route == "/__test__/reset":
            self.state.reset()
            self._send_json(200, {"ok": True})
        elif route == "/__test__/switches":
            self._handle_switches()
        else:
            self._not_found()

    # -- the autocomplete's data -----------------------------------------
    def _handle_directory(self, parsed) -> None:
        state = self.state
        switches = state.switches_snapshot()
        query = parse_qs(parsed.query, keep_blank_values=True).get("q", [None])[0]
        state.note_suggestion_request()
        self._sleep_ms(switches.get("slow_suggest_ms"))

        if switches.get("suggest_empty"):
            # The broken-autocomplete case: typing surfaces nothing at all.
            results: list[dict] = []
        elif query is None:
            results = [dict(entry) for entry in DIRECTORY]
        else:
            results = search_directory(query)
        self._send_json(200, {"query": query or "", "count": len(results), "results": results})

    # -- the send --------------------------------------------------------
    def _handle_send(self) -> None:
        state = self.state
        switches = state.switches_snapshot()
        payload = self._read_json()
        state.note_send_post()
        self._sleep_ms(switches.get("slow_send_ms"))

        if payload is None:
            state.note_rejected()
            self._send_json(400, {"error": "body must be a JSON object"})
            return
        recipients = payload.get("to")
        if isinstance(recipients, str):
            recipients = parse_recipients(recipients)
        if not isinstance(recipients, list):
            state.note_rejected()
            self._send_json(400, {"error": "'to' must be a list of addresses"})
            return
        addresses = [str(address).strip().lower() for address in recipients if str(address).strip()]
        strangers = [address for address in addresses if not is_synthetic(address)]
        if strangers:
            state.note_rejected()
            self._send_json(400, {"error": f"addresses must be @example.test: {strangers[0]}"})
            return

        body = payload.get("body")
        source = payload.get("source") or "gmail-compose"
        message = state.store.send(addresses, str(body or ""), str(source))
        self._send_json(
            200, {"ok": True, "message": message, "sends": state.store.counts()["sends"]}
        )

    # -- a widget's Save --------------------------------------------------
    def _handle_save(self) -> None:
        state = self.state
        payload = self._read_json()
        state.note_save_post()

        if payload is None:
            state.note_rejected()
            self._send_json(400, {"error": "body must be a JSON object"})
            return
        source = payload.get("source")
        fields = payload.get("fields")
        if not isinstance(source, str) or not source:
            state.note_rejected()
            self._send_json(400, {"error": "'source' must name the widget"})
            return
        if not isinstance(fields, dict) or not fields:
            state.note_rejected()
            self._send_json(400, {"error": "'fields' must be a non-empty object"})
            return

        values = state.store.save(source, fields)
        self._send_json(200, {"ok": True, "source": source, "values": values})

    # -- the switches -----------------------------------------------------
    def _handle_switches(self) -> None:
        patch = self._read_json()
        if patch is None:
            self._send_json(400, {"error": "body must be a JSON object"})
            return
        for key in ("slow_suggest_ms", "slow_send_ms"):
            if key in patch and (not isinstance(patch[key], int) or patch[key] < 0):
                self._send_json(400, {"error": f"{key} must be a non-negative integer"})
                return
        for key in ("suggest_empty", "no_toast"):
            if key in patch and not isinstance(patch[key], bool):
                self._send_json(400, {"error": f"{key} must be a boolean"})
                return
        self._send_json(200, {"switches": self.state.merge_switches(patch)})


class WidgetCorpusServer(ThreadingHTTPServer):
    daemon_threads = True
    allow_reuse_address = True

    def __init__(self, address, handler, state: FixtureState) -> None:
        self.state = state
        super().__init__(address, handler)


def make_server(port: int = 0, state: FixtureState | None = None) -> WidgetCorpusServer:
    """Build the fixture server. Tests use it and drive it in-process."""
    return WidgetCorpusServer(("127.0.0.1", port), WidgetCorpusHandler, state or FixtureState())


def main(argv=None) -> int:
    parser = argparse.ArgumentParser(description="Run the synthetic widget-corpus fixture.")
    parser.add_argument("--port", type=int, default=0, help="port (0 picks a free one)")
    args = parser.parse_args(argv)

    server = make_server(args.port)
    port = server.server_port

    # One line, on stdout, before serving: the same shape the messy-crm and
    # lead-crm fixtures print, so a caller that parses one parses this one.
    print(
        json.dumps(
            {
                "url": f"http://127.0.0.1:{port}",
                "port": port,
                "crm_url": f"http://127.0.0.1:{port}",
                "crm_port": port,
            }
        ),
        flush=True,
    )

    try:
        server.serve_forever()
    except KeyboardInterrupt:
        pass
    finally:
        server.server_close()
    return 0


if __name__ == "__main__":
    raise SystemExit(main())
