"""Synthetic widget corpus fixture: a stdlib-only web site for PL-018's tests.

The corpus is one page per shape the recorder has to survive, so a recorder bug
has somewhere local and synthetic to reproduce itself:

* ``gmail-compose.html`` -- the golden: a combobox whose suggestion becomes a
  chip, a ``contenteditable`` body whose text the page writes itself (no
  ``input`` event is ever dispatched), a Send that posts JSON, and a
  ``role="status"`` toast that is the commit's observation.
* ``plain-editor.html`` -- the baseline: a ``contenteditable`` that fires
  ``input`` normally.
* ``framework-editor.html`` -- a ``contenteditable`` mutated by script from
  ``keydown`` and on a timer, with no ``input`` event at all.
* ``react-autocomplete.html`` -- an autocomplete accepted only by clicking the
  option; Enter and Tab do nothing.
* ``shadow-form.html`` -- a form inside an **open** shadow root.
* ``iframe-form.html`` -- a form inside a **same-origin** frame served here.
* ``chip-removal.html`` -- chips with **no** remove control of their own (the
  R2 case) and a compose whose Ctrl+Enter sends with no ``submit`` (R1).
* ``perf.html`` -- 1000 labelled inputs, generated by script.

Everything is in memory, there is no network egress, and the data is synthetic
(``@example.test``; the store refuses anything else). Run it directly to see
the JSON handshake line on stdout::

    python server.py --port 0

Tests use :func:`make_server` and drive the server in-process. ``/index.html``
is rendered here, because the corpus's index is the only page that is not a
widget; every widget is a file under ``public/``.
"""

