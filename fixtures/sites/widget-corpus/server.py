class FixtureState:
    """Everything the handler shares: the store, the switches, the counters."""

    def __init__(self) -> None:
        self.store = WidgetStore()
        self.switches: dict[str, object] = dict(DEFAULT_SWITCHES)
        self.suggest_requests = 0  # GET /directory.json requests handled
        self.send_posts = 0  # POST /send requests handled
        self.save_posts = 0  # POST /save requests handled
        self.rejected = 0  # requests refused before storing anything
        self.lock = threading.Lock()

    # -- switches ---------------------------------------------------------
    def switches_snapshot(self) -> dict[str, object]:
        with self.lock:
            return dict(self.switches)

    def merge_switches(self, patch: dict) -> dict[str, object]:
        with self.lock:
            for key, value in patch.items():
                self.switches[key] = value
            return dict(self.switches)

    def clear_switches(self) -> None:
        with self.lock:
            self.switches = dict(DEFAULT_SWITCHES)

    # -- counters ---------------------------------------------------------
    def note_suggestion_request(self) -> None:
        with self.lock:
            self.suggest_requests += 1

    def note_send_post(self) -> None:
        with self.lock:
            self.send_posts += 1

    def note_save_post(self) -> None:
        with self.lock:
            self.save_posts += 1

    def note_rejected(self) -> None:
        with self.lock:
            self.rejected += 1

    def reset(self) -> None:
        self.store.reset()
        with self.lock:
            self.switches = dict(DEFAULT_SWITCHES)
            self.suggest_requests = 0
            self.send_posts = 0
            self.save_posts = 0
            self.rejected = 0

    def state_payload(self) -> dict:
        """The fixture's own truth: what was really sent and saved."""
        with self.lock:
            switches = dict(self.switches)
            counters = {
                "suggest_requests": self.suggest_requests,
                "send_posts": self.send_posts,
                "save_posts": self.save_posts,
                "rejected": self.rejected,
            }
        payload: dict = {
            "switches": switches,
            "directory_size": len(DIRECTORY),
            "widgets": [source for _path, source, _what in WIDGET_PAGES],
        }
        payload.update(counters)
        payload.update(self.store.counts())
        return payload


