    ("/react-autocomplete.html", "react-autocomplete", "accepted only by clicking the option"),
    ("/shadow-form.html", "shadow-form", "a form inside an open shadow root"),
    ("/iframe-form.html", "iframe-form", "a form inside a same-origin frame"),
    ("/chip-removal.html", "chip-removal", "removal without a control, and a Ctrl+Enter send"),
    ("/perf.html", "perf", "1000 labelled inputs, generated by script"),
